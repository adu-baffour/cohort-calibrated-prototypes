# ------------------------------------------------------------------------------------------------------------------- OSCR / FPR95
def oscr() -> str:
    t = L(FR)["tables"]
    head = ["Host", "Row", "OSCR 1-shot", "FPR95 1-shot", "OSCR 5-shot", "FPR95 5-shot"]
    blocks = []
    for part, title in (("C", "mini-ImageNet and tieredImageNet hosts of rounds (i)-(iv), re-evaluated in round (vii)"), ("A", "CIFAR-FS (round (vii))"),
                        ("B", "mini-ImageNet hosts on CUB (round (vii))")):
        rows = []
        for host, shots in t[part].items():
            for row in shots["1"]["rows"]:
                rows.append([host, row] + [val(shots[str(sh)]["rows"][row], k) for sh in SH for k in ("oscr", "fpr95")])
        blocks.append(section(title, "", md_table(head, rows), f"`{FR}` (`tables / {part}`)"))
    s = L(FM)["summaries"]
    for b, bl in FM_HOSTS.items():
        rows = []
        for ds, dl in FM_DATA.items():
            pre = f"{ds}_{b}|T|1|"
            for row in [k[len(pre):] for k in s if k.startswith(pre)]:
                rows.append([dl, row] + [ci(s[f"{ds}_{b}|T|{sh}|{row}"][k], s[f"{ds}_{b}|T|{sh}|{row}"][f"{k}_ci95"]) for sh in SH
                                         for k in ("oscr", "fpr95")])
        blocks.append(section(f"{bl} (round (viii))", "", md_table(["Dataset"] + head[1:], rows), f"`{FM}` (`summaries / <dataset>_{b}|T|<shot>|<row>`)"))
    return doc("OSCR and FPR95", "OSCR (higher is better) and FPR95 (lower is better) in %, mean ± 95% CI over 600 test episodes (seeded hosts: "
               "mean ± standard deviation over seeds, marked (s)). A query is accepted when u(q) <= tau; FPR95 sets tau at the 72nd smallest of "
               "the 75 known scores of the episode. Rounds (i)-(vi) did not record OSCR or FPR95; round (vii) re-evaluated their configurations "
               "and reproduced their recorded AUROC and accuracy exactly.", *blocks)


# ------------------------------------------------------------------------------------------------------------------- baselines
def setting(v: str) -> str:
    parts = v.split("/")[1:]
    return ", ".join(p.replace("temperature=", "temperature ").replace("sign=", "sign ").replace("delta=", "δ = ").replace("alpha=", "α = ")
                     .replace("k=", "k = ") for p in parts) or "--"


def baselines() -> str:
    bs, cf, fm = L(BSEL)["chosen"], L(CSEL)["chosen"], L(FSEL)["chosen"]
    hosts = [("mini-ImageNet", "frozen FEAT", bs["frozen FEAT mini"]), ("mini-ImageNet", "SnaTCHer-F", bs["SnaTCHer-F mini"]),
             ("mini-ImageNet", "DNPG (seeds 0-2)", bs["DNPG mini"]), ("tieredImageNet", "frozen FEAT", bs["frozen FEAT tiered"]),
             ("CIFAR-FS", "RFS", cf), ("CUB (mini-ImageNet hosts)", "frozen FEAT, SnaTCHer-F, DNPG", "the mini-ImageNet settings")]
    hosts += [(FM_DATA[ds], FM_HOSTS[b], fm[f"{ds}_{b}"]) for b in FM_HOSTS for ds in FM_DATA]
    cols = ["kNN", "RMD", "NNN", "QB-Norm IS", "QB-Norm DIS"]
    rows = []
    for ds, h, ch in hosts:
        if isinstance(ch, str):
            rows.append([ds, h] + [ch] + [""] * (len(cols) - 1))
            continue
        by = {family(v): v for v in ch.values()}
        assert all(setting(by[f]) == "--" for f in ("query cohort term", "CL2N", "ZN", "TEEN"))
        rows.append([ds, h] + [setting(by[c]) for c in cols])
    a = section("Selected settings (former Supplementary Table S9)", "Chosen on valA by mean AUROC over both shots (DNPG: and seeds 0-2), before "
                "any test pass; the query cohort term, CL2N, ZN, TEEN and episode CSLS have no setting. Transfer to CUB keeps the settings "
                "selected on mini-ImageNet (checked against the recorded round (vii) rows).",
                md_table(["Dataset", "Host", *cols], rows), f"`{BSEL}`, `{CSEL}`, `{FSEL}` (`chosen`)")
    import scripts.make_tables as MT
    rows = []
    for g, lab, sh, dd in MT.baseline_cells():
        rows.append([g, lab, sh] + [ci(*dd[f]) for f in FAMILIES])
    b = section("CCP minus each baseline, every ResNet-12 configuration (Table 5 with CIs)", "Paired test AUROC difference CCP - baseline (points), "
                "mean ± 95% CI over 600 episodes; CCP = CCP-A on frozen hosts and H_fix on trained hosts, with each baseline fused with the host "
                "score by fixed-weight fusion on trained hosts.", md_table(["Group", "Host", "Shot", *FAMILIES], rows),
                f"`{BT}` (`paired_test / <host> / <shot> / <row> / minus_CCP`), `{FR}` (`tables / A`), `results/derived/paired_derived.json` (`cub`)")
    r = L(BT)["test"]
    blocks = [a, b]
    for host in r:
        rows = []
        for k in r[host]["1"]:
            rows.append([k] + [val(r[host][str(sh)][k], m) for sh in SH for m in ("auroc", "acc")])
        blocks.append(section(f"Round (v) test rows: {host}", "", md_table(["Row", "AUROC 1-shot", "Acc. 1-shot", "AUROC 5-shot", "Acc. 5-shot"], rows),
                              f"`{BT}` (`test / {host}`)"))
    return doc("Training-free baselines", "Baselines as in Section 4.4 of the paper; nine families, QB-Norm IS and DIS listed separately (identical "
               "in every configuration).", *blocks)


# ------------------------------------------------------------------------------------------------------------------- checkpoints
def checkpoints() -> str:
    rows = []
    for p in sorted((ROOT / "configs" / "hosts").glob("*.yaml")):
        y = yaml.safe_load(p.read_text(encoding="utf-8"))
        cks = y.get("checkpoints") or ({"checkpoint": y["checkpoint"]} if y.get("checkpoint") else {})
        if y.get("backbone_init"):
            cks = {"backbone initialization": y["backbone_init"], **cks}
        for name, ck in cks.items():
            rows.append([y["name"], y.get("dataset", ""), name, f"`{ck.get('path', '')}`", f"`{ck.get('sha256', '')}`", ck.get("source") or "this work (not redistributed; docs/checkpoints.md)"])
    a = section("Host checkpoints", "Every checkpoint the hosts load, with its sha256 (checked before loading). Release asset (ours): FRN, DNPG "
                "and the RFS CIFAR-FS backbone were trained for this work (the RFS checkpoint is not redistributed; see docs/checkpoints.md). "
                "Third-party weights are linked to their authors and not redistributed.",
                md_table(["Host", "Dataset", "Checkpoint", "Path", "sha256", "Source"], rows), "`configs/hosts/*.yaml`")
    rows = []
    for p in sorted((ROOT / "configs" / "hosts").glob("*.yaml")):
        y = yaml.safe_load(p.read_text(encoding="utf-8"))
        b = y.get("bank") or {}
        for shot, e in ([("-", b)] if "file" in b else [(k, v) for k, v in b.items() if isinstance(v, dict)]):
            rows.append([y["name"], shot, f"`{e['file']}`", f"`{e.get('sha256') or ''}`"])
    b = section("Cohort banks", "Not uploaded: `python scripts/build_bank.py --host <host>` (or `--all`) rebuilds each bank under $CCP_ASSETS "
                "byte-identically to the sha256 below, which every evaluation checks before use. Foundation-model and RFS banks: "
                "`python scripts/rounds/foundation_round.py build-banks`, `python scripts/rounds/final_round.py build-banks`.",
                md_table(["Host", "Shot", "File", "sha256"], rows), "`configs/hosts/*.yaml` (`bank`)")
    return doc("Checkpoint and bank checksums", "", a, b)


