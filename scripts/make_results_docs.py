def ci(m, e, d=2) -> str:
    return f"{m:.{d}f} ± {e:.{d}f}"


def sgn(x, d=2) -> str:
    return f"{x:+.{d}f}"


def val(x: dict, metric: str) -> str:
    """'mean ± CI' of a recorded row; a seeded row stores {mean, std}: 'mean ± std (s)'."""
    if isinstance(x[metric], dict):
        return f"{x[metric]['mean']:.2f} ± {x[metric]['std']:.2f} (s)"
    return ci(x[metric], x[f"{metric}_ci95"])


def md_table(head: list[str], rows: list[list[str]]) -> list[str]:
    out = ["| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|"]
    return out + ["| " + " | ".join(str(c).replace("|", "\\|") for c in r) + " |" for r in rows]


def doc(title: str, intro: str, *blocks) -> str:
    out = [f"# {title}", "", "Generated by `python scripts/make_results_docs.py` from the recorded results; do not edit by hand.", ""]
    if intro:
        out += [intro, ""]
    for b in blocks:
        out += b + [""]
    return "\n".join(out)


def section(title, intro, table, source) -> list[str]:
    return [f"## {title}", ""] + ([intro, ""] if intro else []) + table + ["", f"Source: {source}."]


def met(ok: dict) -> str:
    yes, no = [k for k, v in ok.items() if v], [k for k, v in ok.items() if not v]
    return "Met: " + (", ".join(yes) or "none") + ("; not met: " + ", ".join(no) if no else "")


def family(k: str) -> str:
    k = k[6:-1] if k.startswith("fused[") else k
    return k.split("/")[0]


